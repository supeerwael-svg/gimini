/*
# Fix: Invitation Code Generation — Use Schema-Qualified pgcrypto

## Problem
The original create_invitation_code used `gen_random_bytes(6)` (from pgcrypto)
but the function's search_path is set to `public`, and pgcrypto lives in the
`extensions` schema. The call failed with "function gen_random_bytes(integer)
does not exist".

Migration 0005 worked around this by replacing gen_random_bytes with
gen_random_uuid()-based code generation. While functional, the task requires
using the correct schema-qualified pgcrypto function for stronger
cryptographic entropy (48 bits from 6 random bytes vs. a UUID which is
not designed as a CSPRNG).

## Fix
Recreate create_invitation_code using `extensions.gen_random_bytes(6)` —
schema-qualified so the function resolves regardless of search_path.
This produces 6 random bytes (48 bits of entropy), base16-encoded and
uppercased, yielding a 12-character hex code. We take the first 8 characters
for a compact, human-readable invitation code while retaining strong
randomness from pgcrypto's CSPRNG.

No other function, table, policy, or grant is changed. All existing objects
are preserved.

## Security
- Invitation codes remain generated by a CSPRNG (pgcrypto gen_random_bytes).
- Code uniqueness is enforced by the UNIQUE constraint on invitation_codes.code.
- If a collision occurs (astronomically unlikely with 48 bits), the insert
  will fail and the caller can retry — the function does not silently
  overwrite an existing code.
*/

create or replace function public.create_invitation_code(
  p_institution_id uuid,
  p_expires_at timestamptz,
  p_max_uses int default 1
)
returns public.invitation_codes
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text;
  v_row public.invitation_codes%rowtype;
begin
  if not public.has_permission(p_institution_id, 'manage_invitations') then
    raise exception 'You do not have permission to manage invitation codes.';
  end if;

  if p_max_uses < 1 then
    raise exception 'max_uses must be at least 1.';
  end if;

  if p_expires_at <= now() then
    raise exception 'expires_at must be in the future.';
  end if;

  -- Generate a cryptographically random 8-char code via pgcrypto.
  -- Schema-qualified: pgcrypto is in the extensions schema.
  v_code := upper(substr(encode(extensions.gen_random_bytes(6), 'hex'), 1, 8));

  insert into public.invitation_codes (institution_id, code, created_by, expires_at, max_uses)
  values (p_institution_id, v_code, auth.uid(), p_expires_at, p_max_uses)
  returning * into v_row;

  perform public.write_audit(
    p_institution_id, auth.uid(), 'invitation_code_created',
    'invitation_code', v_row.id::text,
    jsonb_build_object('code', v_code, 'max_uses', p_max_uses)
  );

  return v_row;
end;
$$;

-- Preserve the EXECUTE grant state: authenticated only
revoke execute on function public.create_invitation_code(uuid, timestamptz, int) from public, anon;
grant execute on function public.create_invitation_code(uuid, timestamptz, int) to authenticated;
